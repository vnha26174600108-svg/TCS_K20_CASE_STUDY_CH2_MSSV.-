# Bài 8: f-string và định dạng đầu ra
ma_may = "PC12"
cong_suat_w = 250
dien_nang_kwh = 0.375
chi_phi = 1125

# Dùng f-string để in đúng định dạng theo yêu cầu
print(f"Máy: {ma_may}")
print(f"Công suất: {cong_suat_w:.2f} W")
print(f"Điện năng: {dien_nang_kwh} kWh")
print(f"Chi phí: {chi_phi:.2f} VND")